import { Card, CardContent, CardDescription, CardHeader, SkeletonGlass } from "@forth-urban/ui";
import { MarkdownRenderer } from "../../components/markdown-renderer";
import { Sparkles } from "lucide-react";

interface AiExplanationProps {
  title?: string;
  isLoading: boolean;
  isError: boolean;
  text?: string;
  className?: string;
}

/**
 * Renders an LLM Advisory Layer explanation on top of Decision Engine
 * numbers, with a graceful loading/error fallback so a provider outage never
 * blocks the user from seeing the (already-displayed) numbers themselves
 * (docs/IMPLEMENTATION_PLAN.md Phase 5 exit criteria).
 */
export function AiExplanation({ title = "What this means?", isLoading, isError, text, className }: AiExplanationProps) {
  return (
    <Card className={className}>
      <CardHeader>
        <div className="flex items-center justify-between gap-4">
          <CardDescription>{title}</CardDescription>
          <div className="inline-flex items-center gap-1.5 rounded-full px-3 py-1 text-xs font-semibold" style={{
            backgroundColor: "#d4af37",
            color: "#5C4033",
          }}>
            <Sparkles size={14} />
            Generated by your AI Property Advisor
          </div>
        </div>
      </CardHeader>
      <CardContent>
        {isLoading && (
          <div className="space-y-2">
            <SkeletonGlass className="h-4 w-full" />
            <SkeletonGlass className="h-4 w-5/6" />
            <SkeletonGlass className="h-4 w-4/5" />
          </div>
        )}
        {!isLoading && (isError || !text) && (
          <p className="text-sm text-[#181818]/50">
            We couldn't generate a personalized explanation right now — the numbers above are accurate either way.
          </p>
        )}
        {!isLoading && !isError && text && (
          <div className="text-sm text-[#181818]/80 prose prose-sm prose-headings:font-heading prose-headings:text-[#181818] prose-a:text-[#5C4033] prose-strong:font-bold prose-strong:text-[#181818]">
            <MarkdownRenderer content={text} />
          </div>
        )}
      </CardContent>
    </Card>
  );
}
